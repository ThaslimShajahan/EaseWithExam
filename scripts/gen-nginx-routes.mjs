/**
 * Generates deploy/nginx-easewithexam.conf from the routes declared in
 * src/App.jsx.
 *
 *   node scripts/gen-nginx-routes.mjs            # write the conf
 *   node scripts/gen-nginx-routes.mjs --check    # fail if it is out of date
 *
 * WHY THIS IS GENERATED
 *   Returning a real HTTP 404 from a static SPA means nginx has to know which
 *   paths are real routes and which are not — `try_files ... /index.html`
 *   answers 200 to everything, which is exactly the soft-404 problem being
 *   fixed. So nginx needs the route list.
 *
 *   Hand-maintaining that list is a trap. The failure is silent and backwards:
 *   add a route to App.jsx, forget the conf, and a page that works locally
 *   returns 404 in production. Deriving it from App.jsx and asserting it in the
 *   test suite (src/lib/__tests__/seoRoutes.test.js) means drift breaks CI
 *   instead of breaking the site.
 *
 * WHAT IT EXTRACTS
 *   The first path segment of every ABSOLUTE <Route path="/..."> in App.jsx.
 *   Nested routes are written relative (<Route path="content"> inside /admin),
 *   and must NOT be hoisted: treating them as top-level would make /content and
 *   /papers serve index.html, and React would then render its 404 under a 200 —
 *   reintroducing the soft 404 for 28 paths. Deeper segments need no entry
 *   because their parent prefix already matches.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { PAGE_SEO } from '../src/lib/seo.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const APP  = resolve(ROOT, 'src/App.jsx');
const CONF = resolve(ROOT, 'deploy/nginx-easewithexam.conf');

// The routes scripts/prerender.mjs writes as real directories (dist/about/index.html,
// not dist/about.html) — derived from PAGE_SEO rather than hand-listed a third time,
// same reasoning seoRoutes.test.js already applies to sitemap.xml and prerender.mjs's
// own ROUTES. '/' is excluded: it has its own `location = /` block below, never the
// alternation. '/404' is excluded via noindex — it is metadata-only, never a real route.
export function prerenderedRoutes() {
  return Object.entries(PAGE_SEO)
    .filter(([path, meta]) => path !== '/' && !meta.noindex)
    .map(([path]) => path.slice(1))
    .sort();
}

export function topLevelRoutes(source = readFileSync(APP, 'utf8')) {
  const segs = new Set();
  for (const m of source.matchAll(/<Route\s+[^>]*path="([^"]+)"/g)) {
    const raw = m[1];
    // Absolute paths only. A relative path is a nested child route whose parent
    // prefix already covers it — see the header comment.
    if (!raw.startsWith('/')) continue;
    const seg = raw.slice(1).split('/')[0];
    // '' is the index route, '*' is the catch-all — neither is a real prefix,
    // and the catch-all is precisely what must NOT reach index.html.
    if (!seg || seg === '*') continue;
    if (seg.startsWith(':')) continue;
    segs.add(seg);
  }
  return [...segs].sort();
}

const routes      = topLevelRoutes();
const prerendered = prerenderedRoutes();
const spaOnly     = routes.filter((r) => !prerendered.includes(r));
const prerenderedAlternation = prerendered.join('|');
const spaOnlyAlternation     = spaOnly.join('|');

const conf = `# GENERATED by scripts/gen-nginx-routes.mjs — do not edit by hand.
# Regenerate with:  node scripts/gen-nginx-routes.mjs
# Drift is asserted by src/lib/__tests__/seoRoutes.test.js.
#
# Purpose: serve index.html for real app routes, and a genuine HTTP 404 for
# everything else. The previous config answered 200 to every path, so an
# unbounded set of bad URLs returned homepage content — a soft 404.
#
# Place inside the existing server { } block for www.easewithexam.com,
# REPLACING the current catch-all \`location / { try_files $uri $uri/ /index.html; }\`.

# Hashed build assets. Immutable because every filename carries a content hash.
location /assets/ {
    try_files $uri =404;
    expires 1y;
    add_header Cache-Control "public, immutable";
}

# The service worker must never be served stale, or clients pin an old build.
location = /sw.js {
    try_files $uri =404;
    expires -1;
    add_header Cache-Control "no-cache, no-store, must-revalidate";
}

# Prerendered public routes -> their own real file first, THEN the SPA shell.
# \`$uri/\` is what makes this find dist/about/index.html at all — without it,
# nginx never resolves the directory and falls straight to the root
# index.html, so the page silently serves the HOMEPAGE's title and canonical
# instead of its own. That exact regression shipped 2026-08-15 (this location
# block existed but only tried \`$uri\`) and stood for 4 days undetected because
# verification only checked HTTP status codes, which were 200 either way —
# see docs/DEPLOY.md's standing content-verification step.
location ~ ^/(${prerenderedAlternation})(/|$) {
    try_files $uri $uri/ /index.html;
}

# Pure client-only routes (no prerendered file exists) -> straight to the SPA
# shell, same as before. \`$\` anchors each alternative so /aboutxyz does not
# match /about.
location ~ ^/(${spaOnlyAlternation})(/|$) {
    try_files $uri /index.html;
}

# The site root.
location = / {
    try_files /index.html =404;
}

# Everything else: a real file if one exists, otherwise a real 404.
location / {
    try_files $uri $uri/ =404;
}

error_page 404 /404.html;
location = /404.html {
    internal;
}
`;

// Only act when run as a CLI. The test suite imports topLevelRoutes() from
// here, and an import that rewrites a tracked file as a side effect would make
// `vitest run` produce a dirty working tree.
const isCli = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (!isCli) {
  // no-op: imported for topLevelRoutes()
} else if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(CONF, 'utf8'); } catch { /* missing */ }
  if (current !== conf) {
    console.error('deploy/nginx-easewithexam.conf is out of date.');
    console.error('Run: node scripts/gen-nginx-routes.mjs');
    process.exit(1);
  }
  console.log(`nginx conf up to date (${routes.length} route prefixes).`);
} else {
  mkdirSync(dirname(CONF), { recursive: true });
  writeFileSync(CONF, conf);
  console.log(`wrote deploy/nginx-easewithexam.conf — ${routes.length} route prefixes:`);
  console.log(`  ${routes.join(' ')}`);
}
